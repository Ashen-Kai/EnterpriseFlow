import { useState, useEffect } from 'react';
import { FileBarChart, Download, RefreshCw, Loader2 } from 'lucide-react';
import { reportsApi } from '../api';
import { useAuth } from '../context/AuthContext';

export default function Reports() {
  const { isManager } = useAuth();
  const [reports, setReports] = useState([]);
  const [total, setTotal] = useState(0);
  const [page, setPage] = useState(1);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState('');
  const [selectedReport, setSelectedReport] = useState(null);

  useEffect(() => { loadReports(); }, [page]);

  const loadReports = async () => {
    setLoading(true);
    try {
      const res = await reportsApi.getAll({ page, limit: 15 });
      setReports(res.data.data.data);
      setTotal(res.data.data.total);
    } catch (err) { console.error(err); }
    finally { setLoading(false); }
  };

  const handleGenerate = async (type) => {
    setGenerating(type);
    try {
      await reportsApi.generate(type);
      loadReports();
    } catch (err) { alert(err.response?.data?.message || 'Failed to generate report'); }
    finally { setGenerating(''); }
  };

  const typeBadge = (type) => {
    const map = { INVENTORY: 'info', PROCUREMENT: 'warning', HR: 'success', FINANCIAL: 'neutral' };
    return <span className={`badge badge-${map[type] || 'neutral'}`}>{type}</span>;
  };

  const totalPages = Math.ceil(total / 15);

  return (
    <div>
      {/* Generate Buttons */}
      {isManager && (
        <div className="glass-card mb-6 animate-fade-in">
          <div className="card-header">
            <h2 className="card-title">Generate Report</h2>
          </div>
          <div className="card-body">
            <div className="flex gap-3" style={{ flexWrap: 'wrap' }}>
              {['INVENTORY', 'PROCUREMENT', 'HR', 'FINANCIAL'].map((type) => (
                <button
                  key={type}
                  className="btn btn-secondary"
                  onClick={() => handleGenerate(type)}
                  disabled={generating === type}
                >
                  {generating === type ? <Loader2 size={16} className="spin" /> : <RefreshCw size={16} />}
                  {type} Report
                </button>
              ))}
            </div>
          </div>
        </div>
      )}

      {/* Reports Table */}
      <div className="glass-card animate-fade-in stagger-2">
        <div className="card-header">
          <h2 className="card-title">Generated Reports</h2>
          <span className="text-xs text-muted">{total} reports</span>
        </div>

        <div className="table-wrapper">
          <table className="data-table">
            <thead>
              <tr>
                <th>Title</th>
                <th>Type</th>
                <th>Generated By</th>
                <th>Date</th>
                <th>Actions</th>
              </tr>
            </thead>
            <tbody>
              {reports.length === 0 ? (
                <tr>
                  <td colSpan={5}>
                    <div className="empty-state">
                      <FileBarChart />
                      <h3>No reports generated</h3>
                      <p>Generate your first report using the buttons above</p>
                    </div>
                  </td>
                </tr>
              ) : (
                reports.map((report) => (
                  <tr key={report.id}>
                    <td><strong>{report.title}</strong></td>
                    <td>{typeBadge(report.type)}</td>
                    <td>{report.generatedBy?.name}</td>
                    <td>{new Date(report.generatedAt).toLocaleString()}</td>
                    <td>
                      <button
                        className="btn btn-secondary btn-sm"
                        onClick={() => setSelectedReport(selectedReport?.id === report.id ? null : report)}
                      >
                        {selectedReport?.id === report.id ? 'Hide' : 'View Data'}
                      </button>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>

        {totalPages > 1 && (
          <div className="pagination">
            <div className="pagination-info">Page {page} of {totalPages}</div>
            <div className="pagination-controls">
              <button className="pagination-btn" disabled={page <= 1} onClick={() => setPage(page - 1)}>Prev</button>
              <button className="pagination-btn" disabled={page >= totalPages} onClick={() => setPage(page + 1)}>Next</button>
            </div>
          </div>
        )}
      </div>

      {/* Report Viewer */}
      {selectedReport && (
        <div className="glass-card mt-6 animate-fade-in">
          <div className="card-header">
            <h2 className="card-title">{selectedReport.title}</h2>
            <button className="btn btn-secondary btn-sm" onClick={() => setSelectedReport(null)}>Close</button>
          </div>
          <div className="card-body">
            <pre style={{
              background: 'var(--bg-input)',
              padding: 20,
              borderRadius: 'var(--radius-sm)',
              fontSize: '0.8125rem',
              color: 'var(--text-secondary)',
              overflow: 'auto',
              maxHeight: 400,
              lineHeight: 1.6,
            }}>
              {JSON.stringify(selectedReport.data, null, 2)}
            </pre>
          </div>
        </div>
      )}
    </div>
  );
}
